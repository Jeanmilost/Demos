int Platform::GetWidth() const
{
    return m_Width;
}
//------------------------------------------------------------------------------
void Platform::SetWidth(int value)
{
    m_Width = value;
}
//------------------------------------------------------------------------------
int Platform::GetHeight() const
{
    return m_Height;
}
