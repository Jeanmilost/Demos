#include "Platform.h"

//------------------------------------------------------------------------------
// Platform
//------------------------------------------------------------------------------
Platform::Platform()
{}
//------------------------------------------------------------------------------
Platform::Platform(int width, int height) :
    m_Width(width),
    m_Height(height)
{}
//------------------------------------------------------------------------------
Platform::~Platform()
{}
//------------------------------------------------------------------------------
int Platform::GetWidth() const
{
    return m_Width;
}
//------------------------------------------------------------------------------
int Platform::GetHeight() const
{
    return m_Height;
}
//------------------------------------------------------------------------------
float Platform::GetAngle() const
{
    return m_Angle;
}
//------------------------------------------------------------------------------
void Platform::SetAngle(float angle)
{
    m_Angle = angle;
}
